"""
Preparaciones regionales y su deconstrucción en ingredientes (RF4).

Cada componente indica los GRAMOS CRUDOS por porción típica. El método del
componente solo se indica si difiere del de la preparación. Los acompañantes
con método propio (el huevo frito de la bandeja paisa, la arepa asada) lo
declaran explícitamente.

AVISO: recetas tipo para el prototipo, pendientes de validación por el
nutricionista asesor. Las cantidades cambian mucho entre casas y regiones.

Reglas que conviene conocer:
* Si la preparación tiene un componente con rol "grasa_coccion" (el aceite
  del hogao, del calentado), ese aceite ya está contado y la calculadora de
  absorción no suma más: así no se cuenta el aceite dos veces.
* Si el usuario dice otra preparación ("arepa frita"), el método nuevo se
  aplica a los componentes con rol "base".
"""


def C(alimento, gramos, rol="base", metodo=None, opcional=False):
    return {"alimento": alimento, "cantidad_g": gramos, "rol": rol, "metodo": metodo, "opcional": opcional}


def P(nombre, categoria, porcion_g, metodo, componentes, *, region="Andina", variantes=False,
      porciones=None, terminos=(), descripcion="", defecto=None):
    return {
        "nombre": nombre,
        "categoria": categoria,
        "peso_porcion_g": porcion_g,
        "metodo": metodo,
        "componentes": componentes,
        "region": region,
        "admite_variantes": variantes,
        "porciones": porciones or {"porcion": porcion_g},
        "terminos": list(terminos),
        "descripcion": descripcion,
        "porcion_defecto": defecto,
    }


